type WidenMessages<T> = {
  readonly [K in keyof T]: T[K] extends string ? string : WidenMessages<T[K]>
}

export type Messages = WidenMessages<typeof dictionaries.zh>

export const messages: Record<Locale, Messages> = dictionaries

export function getInitialLocale(): Locale {
  if (typeof window === 'undefined') {
    return 'zh'
  }
  const saved = window.localStorage.getItem('real2sim.locale')
  return saved === 'en' ? 'en' : 'zh'
}
